export const STRINGS = { en, ar };

export function pickLang(value) {
  return LANGS.includes(value) ? value : "ar";
}

export function translator(lang) {
  const table = STRINGS[pickLang(lang)];
  return (key, vars = {}) => {
    const s = table[key] ?? en[key] ?? key;
    return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? String(vars[k]) : `{${k}}`));
  };
}
